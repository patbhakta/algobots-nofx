"""Generate formatted markdown report from stock analysis."""

import argparse
from datetime import datetime, timezone
from pathlib import Path

import json


def generate_report(analyses: list[dict]) -> str:
    """Generate a markdown technical analysis report.

    Args:
        analyses: List of analysis dicts from analyzer.analyze_all()

    Returns:
        Formatted markdown string
    """
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines = [
        "# Stock Technical Analysis Report",
        f"**Date:** {now}  ",
        f"**Generated by:** AlgoBots via Kestra  ",
        f"**Tickers:** {', '.join(a['ticker'] for a in analyses)}",
        "",
        "---",
        "",
        "## Summary",
        "",
        "| Ticker | Price | RSI | MACD | Bollinger | Signal | Confidence |",
        "|--------|-------|-----|------|-----------|--------|------------|",
    ]

    for a in analyses:
        signals = a.get("signals", {})
        ticker = a["ticker"]
        price = a["price"]
        rsi = signals.get("RSI", "—")
        macd = signals.get("MACD", "—")
        boll = signals.get("Bollinger", "—")
        rec = a["recommendation"]
        conf = f"{int(a['confidence'] * 100)}%"

        lines.append(f"| {ticker} | ${price:.2f} | {rsi} | {macd} | {boll} | **{rec}** | {conf} |")

    lines.extend(["", "---", "", "## Detailed Analysis", ""])

    for a in analyses:
        ticker = a["ticker"]
        rec = a["recommendation"]
        conf = int(a["confidence"] * 100)
        price = a["price"]
        signals = a.get("signals", {})
        reasons = a.get("reasons", [])

        lines.append(f"### {ticker} — {rec} ({conf}% confidence)")
        lines.append(f"**Current Price:** ${price:.2f}")
        lines.append("")

        lines.append("**Signals:**")
        for indicator, signal in signals.items():
            lines.append(f"- {indicator}: {signal}")
        lines.append("")

        if reasons:
            lines.append("**Reasoning:**")
            for reason in reasons:
                lines.append(f"- {reason}")
            lines.append("")

        lines.append("**Raw Indicators:**")
        indicators = a.get("indicators", {})
        for key, val in indicators.items():
            if val is not None and isinstance(val, (int, float)):
                lines.append(f"- {key}: {val:.4f}")
        lines.append("")
        lines.append("---")
        lines.append("")

    lines.extend([
        "## Disclaimer",
        "",
        "This report is generated automatically for testing purposes only.",
        "It is NOT financial advice. Always do your own research.",
    ])

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generate report")
    parser.add_argument("--input", default="analysis.json")
    parser.add_argument("--output", default="report.md")
    args = parser.parse_args()

    data = json.loads(Path(args.input).read_text())
    report = generate_report(data)
    Path(args.output).write_text(report)
    print(f"Report written to {args.output}")


if __name__ == "__main__":
    main()
