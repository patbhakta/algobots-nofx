// Run through tests/api/test_nofx_browser.py in the API repo. Fixture credentials
// are confined to the isolated test database; no deployed account is accessed.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
;(async () => {
  let input = ''; for await (const chunk of process.stdin) input += chunk
  const {url, email} = JSON.parse(input)
  const browser = await chromium.launch({headless: true, executablePath: process.env.PLAYWRIGHT_EXECUTABLE || undefined, args: ['--no-sandbox']})
  try {
    const page = await browser.newPage({viewport: {width: 1440, height: 1000}})
    const errors = []; const external = []
    page.on('websocket', socket => external.push(socket.url()))
    page.on('pageerror', e => errors.push(e.message))
    page.on('request', r => { if (!r.url().startsWith(url) && !r.url().startsWith('data:') && !['fonts.googleapis.com', 'fonts.gstatic.com'].includes(new URL(r.url()).hostname)) external.push(r.url()) })
    await page.goto(url + '/login')
    await page.locator('input[type=email]').fill(email)
    await page.locator('input[type=password]').fill('correct-horse-battery')
    await page.locator('button[type=submit]').click()
    await page.waitForURL('**/dashboard')
    await page.locator('.tm-box').waitFor()
    const expected = ['Dashboard', 'Data', 'Strategy', 'Leaderboard', 'FAQ', 'Config']
    const nav = () => page.locator('nav.header-bar').locator('button, a').filter({visible:true}).allTextContents()
    const desktop = (await nav()).join('|')
    assert.ok(desktop.indexOf('Dashboard') < desktop.indexOf('Data'), desktop)
    for (let i=1;i<expected.length;i++) assert.ok(desktop.indexOf(expected[i-1]) < desktop.indexOf(expected[i]), desktop)
    await page.setViewportSize({width: 390, height: 844})
    await page.getByRole('button', {name:'Open navigation'}).click()
    const mobile = (await nav()).join('|')
    for (let i=1;i<expected.length;i++) assert.ok(mobile.indexOf(expected[i-1]) < mobile.indexOf(expected[i]), mobile)
    await page.getByRole('button', {name:'Close navigation'}).click()
    await page.setViewportSize({width: 1440, height: 1000})
    await page.waitForTimeout(250)
    if (process.env.NOFX_SCREENSHOT_DIR) await page.screenshot({path:path.join(process.env.NOFX_SCREENSHOT_DIR, 'dashboard-fixture.png'),fullPage:true})
    assert.deepEqual(external, [], 'Paper dashboard contacted an external data provider')
    await page.goto(url + '/strategy')
    await page.getByLabel('Strategy name', {exact:true}).waitFor()
    assert.equal(await page.getByLabel('Entry confidence', {exact:true}).inputValue(), '0', 'Loading changed the saved confidence floor')
    await page.getByLabel('Strategy name', {exact:true}).fill('Review 2 edited strategy')
    const saved = page.waitForResponse(r => r.request().method() === 'PUT')
    await page.getByRole('button', {name:'Save',exact:true}).click()
    const response = await saved
    assert.equal(response.status(), 200)
    const row = await response.json()
    assert.equal(row.config.ai_config.risk_control.min_confidence, 0, 'Saving changed the saved confidence floor')
    await page.reload()
    await page.getByLabel('Strategy name', {exact:true}).waitFor()
    assert.equal(await page.getByLabel('Strategy name', {exact:true}).inputValue(), 'Review 2 edited strategy')
    await page.getByLabel('Entry confidence', {exact:true}).selectOption('75')
    const changed = page.waitForResponse(r => r.request().method() === 'PUT')
    await page.getByRole('button', {name:'Save',exact:true}).click()
    assert.equal((await (await changed).json()).config.ai_config.risk_control.min_confidence,75)
    await page.reload()
    await page.getByLabel('Entry confidence', {exact:true}).waitFor()
    assert.equal(await page.getByLabel('Entry confidence', {exact:true}).inputValue(),'75')
    await page.goto(url + '/competition')
    await page.getByRole('heading', {name:'Scored accounts'}).waitFor()
    await page.getByLabel('Hit rate by account').waitFor()
    await page.getByLabel('Brier score by account').waitFor()
    if (process.env.NOFX_SCREENSHOT_DIR) await page.screenshot({path:path.join(process.env.NOFX_SCREENSHOT_DIR, 'leaderboard-fixture.png'),fullPage:true})
    assert.deepEqual(errors, [])
    console.log('PASS: login lands on upstream dashboard; header order; no external dashboard requests; name and risk edits persist through real PUT/reload; score charts render.')
  } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)})
